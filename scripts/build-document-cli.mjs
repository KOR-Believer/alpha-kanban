#!/usr/bin/env node
import { build } from "esbuild";
import { readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
export async function buildDocumentCli({ check = false } = {}) {
  const result = await build({ absWorkingDir: root, entryPoints: ["scripts/document-cli.mjs"], bundle: true, platform: "node", target: "node24", format: "esm", minify: true, legalComments: "none", write: false, metafile: true });
  const licenses = new Map();
  for (const input of Object.keys(result.metafile.inputs)) {
    if (!input.includes("node_modules/")) continue;
    let directory = path.dirname(path.resolve(root, input));
    for (;;) {
      let metadata;
      try { metadata = JSON.parse(await readFile(path.join(directory, "package.json"), "utf8")); } catch { /* climb to the owning package */ }
      if (metadata?.name) {
        const key = `${metadata.name}@${metadata.version}`;
        if (!licenses.has(key)) {
          let license;
          for (const name of ["LICENSE", "license", "LICENSE.md", "license.md", "LICENSE.txt"]) {
            try { license = await readFile(path.join(directory, name), "utf8"); break; } catch { /* try conventional names */ }
          }
          if (!license) throw new Error("Missing dependency license: " + key);
          licenses.set(key, license.trim());
        }
        break;
      }
      const parent = path.dirname(directory); if (parent === directory) throw new Error("Cannot establish dependency provenance: " + input); directory = parent;
    }
  }
  const outputs = {
    "scripts/document-cli.mjs": result.outputFiles[0].text.replace("#!/usr/bin/env node\n", "#!/usr/bin/env node\n// Generated by scripts/build-document-cli.mjs. See licenses/document-cli.txt.\n"),
    "licenses/document-cli.txt": [...licenses].sort(([a], [b]) => a.localeCompare(b)).map(([name, text]) => name + "\n" + "=".repeat(name.length) + "\n" + text + "\n").join("\n"),
  };
  for (const [name, content] of Object.entries(outputs)) {
    const target = path.join(root, "skills/implementation-ledger", name);
    if (check) { if (await readFile(target, "utf8") !== content) throw new Error("Stale bundled artifact: " + name); }
    else { await mkdir(path.dirname(target), { recursive: true }); await writeFile(target, content); }
  }
  return outputs;
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await buildDocumentCli({ check: process.argv.includes("--check") });
  console.log("Standalone document CLI and dependency licenses verified.");
}
